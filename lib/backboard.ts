export interface AIReviewContent {
  review_summary: string;
  evidence_examined: string[];
  evidence_gaps_and_uncertainties: string;
  recommended_next_actions: string[];
  limitations: string;
}

export interface BackboardResponse {
  content: string;
  thread_id: string;
  assistant_id: string;
}

export interface BackboardError {
  type: 'auth' | 'network' | 'timeout' | 'rate_limit' | 'malformed' | 'server' | 'not_configured';
  message: string;
}

const BACKBOARD_URL = 'https://app.backboard.io/api/threads/messages';
const REQUEST_TIMEOUT_MS = 30000;
const MAX_FIELD_LENGTH = 2000;
const MAX_ARRAY_ITEMS = 20;

export function isBackboardConfigured(): boolean {
  return !!process.env.BACKBOARD_API_KEY;
}

export function buildReviewPrompt(context: {
  findingTitle: string;
  findingDescription: string;
  findingSeverity: string;
  findingStatus: string;
  findingReasoning: string | null;
  controlReference: string | null;
  controlTitle: string | null;
  controlDescription: string | null;
  evidenceItems: { id: string; title: string; description: string | null; status: string; source_type: string | null }[];
  remediationTasks: { title: string; status: string; assignee: string | null }[];
}): string {
  const evidenceLines = context.evidenceItems.length > 0
    ? context.evidenceItems.map((e, i) =>
        `  ${i + 1}. ID: ${e.id} | Title: ${e.title} | Status: ${e.status} | Source: ${e.source_type ?? 'N/A'} | Description: ${e.description ?? 'N/A'}`
      ).join('\n')
    : '  (No evidence items are linked to this finding.)';

  const taskLines = context.remediationTasks.length > 0
    ? context.remediationTasks.map((t, i) =>
        `  ${i + 1}. Title: ${t.title} | Status: ${t.status} | Assignee: ${t.assignee ?? 'Unassigned'}`
      ).join('\n')
    : '  (No remediation tasks have been created for this finding.)';

  return `You are a security compliance review assistant. You are reviewing a finding that was generated by a deterministic rules engine. Your job is to explain the finding, assess the available evidence, identify uncertainties, and recommend practical next steps.

IMPORTANT CONSTRAINTS:
- Do NOT invent evidence, control states, test results, dates, or completed actions.
- Do NOT claim any certification, audit approval, or compliance status.
- Do NOT assign numerical confidence scores.
- Distinguish clearly between "missing evidence" and "proof of noncompliance."
- Your review is advisory and does not replace a human security or compliance review.
- Respond ONLY with valid JSON matching the specified structure. No markdown, no code fences.

FINDING:
  Title: ${context.findingTitle}
  Description: ${context.findingDescription}
  Severity: ${context.findingSeverity}
  Status: ${context.findingStatus}
  Deterministic Reasoning: ${context.findingReasoning ?? 'N/A'}

CONTROL:
  Reference: ${context.controlReference ?? 'N/A'}
  Title: ${context.controlTitle ?? 'N/A'}
  Description: ${context.controlDescription ?? 'N/A'}

LINKED EVIDENCE:
${evidenceLines}

REMEDIATION TASKS:
${taskLines}

Respond with EXACTLY this JSON structure (no other text):
{
  "review_summary": "What the existing finding indicates, based on the records above.",
  "evidence_examined": ["List of evidence titles or IDs that were actually examined"],
  "evidence_gaps_and_uncertainties": "What cannot be established from the available information.",
  "recommended_next_actions": ["Specific, practical steps to improve or verify the situation"],
  "limitations": "A concise statement of what the current records cannot prove."
}`;
}

export async function callBackboard(
  prompt: string,
  apiKey: string
): Promise<{ content: string; thread_id: string | null; model: string | null }> {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  try {
    const response = await fetch(BACKBOARD_URL, {
      method: 'POST',
      headers: {
        'X-API-Key': apiKey,
        'Content-Type': 'application/json',
      },
      signal: controller.signal,
      body: JSON.stringify({
        content: prompt,
        stream: false,
      }),
    });

    if (response.status === 401) {
      return Promise.reject({
        type: 'auth' as const,
        message: 'Backboard API key is invalid or unauthorized.',
      });
    }

    if (response.status === 429) {
      return Promise.reject({
        type: 'rate_limit' as const,
        message: 'Backboard API rate limit exceeded. Please try again later.',
      });
    }

    if (response.status >= 500) {
      return Promise.reject({
        type: 'server' as const,
        message: 'Backboard API returned a server error. Please try again later.',
      });
    }

    if (!response.ok) {
      return Promise.reject({
        type: 'server' as const,
        message: `Backboard API returned status ${response.status}.`,
      });
    }

    const data = await response.json();

    if (!data || typeof data.content !== 'string' || data.content.length === 0) {
      return Promise.reject({
        type: 'malformed' as const,
        message: 'Backboard API returned an empty or malformed response.',
      });
    }

    return {
      content: data.content,
      thread_id: typeof data.thread_id === 'string' ? data.thread_id : null,
      model: typeof data.model_name === 'string' ? data.model_name : null,
    };
  } catch (err) {
    if (err instanceof DOMException && err.name === 'AbortError') {
      return Promise.reject({
        type: 'timeout' as const,
        message: 'Backboard API request timed out.',
      });
    }
    if (err && typeof err === 'object' && 'type' in err) {
      return Promise.reject(err);
    }
    return Promise.reject({
      type: 'network' as const,
      message: 'Unable to reach the Backboard API.',
    });
  } finally {
    clearTimeout(timeout);
  }
}

export function parseReviewContent(raw: string): AIReviewContent | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    const jsonMatch = raw.match(/\{[\s\S]*\}/);
    if (!jsonMatch) return null;
    try {
      parsed = JSON.parse(jsonMatch[0]);
    } catch {
      return null;
    }
  }

  if (!parsed || typeof parsed !== 'object') return null;
  const obj = parsed as Record<string, unknown>;

  const reviewSummary = obj.review_summary;
  const evidenceExamined = obj.evidence_examined;
  const evidenceGaps = obj.evidence_gaps_and_uncertainties;
  const recommendedActions = obj.recommended_next_actions;
  const limitations = obj.limitations;

  if (typeof reviewSummary !== 'string' || reviewSummary.trim().length === 0) return null;
  if (typeof evidenceGaps !== 'string' || evidenceGaps.trim().length === 0) return null;
  if (typeof limitations !== 'string' || limitations.trim().length === 0) return null;

  if (!Array.isArray(evidenceExamined)) return null;
  if (!Array.isArray(recommendedActions)) return null;

  const cleanEvidence = evidenceExamined
    .filter((e): e is string => typeof e === 'string' && e.trim().length > 0)
    .slice(0, MAX_ARRAY_ITEMS);
  const cleanActions = recommendedActions
    .filter((a): a is string => typeof a === 'string' && a.trim().length > 0)
    .slice(0, MAX_ARRAY_ITEMS);

  return {
    review_summary: reviewSummary.trim().slice(0, MAX_FIELD_LENGTH),
    evidence_examined: cleanEvidence.map((e) => e.trim().slice(0, 500)),
    evidence_gaps_and_uncertainties: evidenceGaps.trim().slice(0, MAX_FIELD_LENGTH),
    recommended_next_actions: cleanActions.map((a) => a.trim().slice(0, 500)),
    limitations: limitations.trim().slice(0, MAX_FIELD_LENGTH),
  };
}
